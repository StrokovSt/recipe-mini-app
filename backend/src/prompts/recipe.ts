import { UNIT_CODES } from "@recipe/common";

// Списки пользователя: AI выбирает категорию и теги только из них
export interface PromptContext {
    categories: string[];
    tags: string[];
}

const UNIT_HINTS = `g — граммы, kg — килограммы, oz — унции, lb — фунты,
ml — миллилитры, l — литры, tsp — чайная ложка, tbsp — столовая ложка,
glass — стакан (русский, 200–250 мл), cup_us — американская чашка (cup),
pcs — штуки, clove — зубчик, slice — ломтик, bunch — пучок, sprig — веточка,
can — банка, pack — упаковка/пачка/пакетик, pinch — щепотка, handful — горсть,
to_taste — «по вкусу»`;

const sharedRules = ({ categories, tags }: PromptContext) => `
ПОЛЯ:
- title: название блюда
- description: короткое описание блюда в 1–2 предложения, если в источнике есть вступление или описание; иначе null. Не выдумывай
- category: ровно одно название из списка категорий пользователя или null, если ни одна не подходит
- tags: 0–5 тегов, только из списка тегов пользователя, дословно. Новые теги не придумывай
- prepTime: подготовка в минутах (нарезка, замес, маринование), только если указано, иначе null
- cookTime: готовка в минутах (варка, жарка, выпечка), только если указано. Если указано одно общее время — запиши его в cookTime, prepTime null
- servings: количество порций числом, только если указано, иначе null
- steps: шаги приготовления, каждый шаг отдельной строкой, без номеров

ИНГРЕДИЕНТЫ:
- ingredients: массив групп. Если ингредиенты разбиты на группы ("Для теста:", "Для крема:") — отдельная группа для каждой с title, иначе одна группа с title: null
- каждый ингредиент — объект { "name", "amount", "unit" }
- name: название продукта на языке рецепта, без количества и единиц ("мука пшеничная", "яйца")
- amount: число (дроби десятичной точкой: 1/2 → 0.5, 1 1/2 → 1.5). Диапазон "2–3" → нижнее число 2. Нет количества → null
- unit: один код из списка единиц или null. "2 ст. л." → amount 2, unit "tbsp"; "3 яйца" → amount 3, unit "pcs"; "соль по вкусу" → amount null, unit "to_taste"
- если единицы нет в списке, перенеси её в name ("2 стебля сельдерея" → name "сельдерей, стебли", amount 2, unit null)

ЕДИНИЦЫ (коды): ${UNIT_CODES.join(", ")}
${UNIT_HINTS}

КАТЕГОРИИ ПОЛЬЗОВАТЕЛЯ: ${categories.length ? categories.map((name) => `"${name}"`).join(", ") : "нет"}
ТЕГИ ПОЛЬЗОВАТЕЛЯ: ${tags.length ? tags.map((name) => `"${name}"`).join(", ") : "нет"}

Формат ответа:
{
    "title": "название",
    "description": null,
    "category": "Супы",
    "ingredients": [
        { "title": null, "items": [{ "name": "мука", "amount": 200, "unit": "g" }, { "name": "соль", "amount": null, "unit": "to_taste" }] },
        { "title": "Для крема", "items": [{ "name": "сливки 33%", "amount": 300, "unit": "ml" }] }
    ],
    "steps": ["шаг 1", "шаг 2"],
    "prepTime": 15,
    "cookTime": 30,
    "servings": 2,
    "tags": ["быстро"]
}
`;

export const recipePrompt = (text: string, context: PromptContext) => `
Ты парсер рецептов. Извлеки данные из текста и верни ТОЛЬКО валидный JSON без markdown и пояснений.

Игнорируй мусор: HTML теги как разметку (<b>, <i> и т.п.), ссылки (http, t.me, @username), призывы ("подпишись", "переходи"), рекламу и промо, комментарии других пользователей, названия каналов и групп.
Если название не найдено — придумай по ингредиентам. Ищи шаги, даже если они идут списком без заголовка "Приготовление".
${sharedRules(context)}
Текст: ${text}
`;

export const recipeImagePrompt = (context: PromptContext) => `
Ты парсер рецептов. Посмотри на изображение и извлеки данные рецепта. Верни ТОЛЬКО валидный JSON без markdown и пояснений.

Если название не видно — придумай по содержимому. Если шагов не видно — steps: [].
${sharedRules(context)}`;
